type NutritionRow = [kcal: number, protein: number, fat: number, carb: number, name: string];
const TABLE = NUTRITION as unknown as Record<string, NutritionRow>;

function nutritionOf(ref: string | null): Pick<Food, 'per100' | 'nutritionSource' | 'nutritionRef'> {
  if (ref === 'zero') return { per100: { kcal: 0, protein: 0, fat: 0, carb: 0 }, nutritionSource: 'manual' };
  const n = ref ? TABLE[ref] : undefined;
  if (!ref || !n) return { per100: null, nutritionSource: 'manual' };
  return {
    per100: { kcal: n[0], protein: n[1], fat: n[2], carb: n[3] },
    nutritionSource: ref.startsWith('usda:') ? 'usda' : 'tw',
    nutritionRef: ref,
  };
}

export function seedFoods(): Food[] {
  return ROWS.map(([id, name, aliases, section, kind, baseUnit, gPerBase, ref, shelf, defaultLocation, conversions, purchaseUnit]) => ({
    id: 'f_' + id,
    name,
    aliases,
    pinyinInitials: buildInitials(name, aliases),
    section,
    sectionLearned: false,
    kind,
    baseUnit,
    gPerBase,
    conversions: conversions ?? [],
    ...nutritionOf(ref),
    shelfDays: shelf,
    defaultLocation,
    purchaseUnit,
  }));
}
